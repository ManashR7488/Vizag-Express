#!/usr/bin/env node
/* ==========================================================================
   VIZAG EXPRESS — PLACE PAGES
   Writes a themed, fully static page for every place in js/data.js:
     places/<id>/index.html   (own SEO tags, share image, structured data)
   Usage: npm run places   (part of `npm run build`)
   ========================================================================== */
"use strict";
const { fs, file, loadData, siteUrl, today } = require("./lib");
const { placePage, pageUrl, imgSrc } = require("./place-templates");

const { SITE, TRIP, PLACES, DAYS } = loadData();
const URL_ = siteUrl(SITE);

// where the facts on each page come from (shown in the page footer)
const SOURCES = {
  "simhachalam-temple": [["Wikipedia: Simhachalam", "https://en.wikipedia.org/wiki/Simhachalam"]],
  "ross-hill-church": [["Yo! Vizag", "https://www.yovizag.com/temples-in-vizag-srikakulam-vizianagaram-east-godavari/"], ["Holidify", "https://www.holidify.com/places/visakhapatnam/ross-hill-church-sightseeing-124851.html"]],
  "rk-beach": [["Wikipedia: Ramakrishna Beach", "https://en.wikipedia.org/wiki/Ramakrishna_Beach"]],
  "ins-kursura-submarine-museum": [["Wikipedia: INS Kursura", "https://en.wikipedia.org/wiki/INS_Kursura"]],
  kailasagiri: [["Wikipedia: Kailasagiri", "https://en.wikipedia.org/wiki/Kailasagiri"]],
  "tenneti-park": [["Wikipedia: Tenneti Park", "https://en.wikipedia.org/wiki/Tenneti_Park"]],
  "indira-gandhi-zoological-park": [["Wikipedia: Indira Gandhi Zoological Park", "https://en.wikipedia.org/wiki/Indira_Gandhi_Zoological_Park"]],
  "rushikonda-beach": [["Wikipedia: Rushikonda Beach", "https://en.wikipedia.org/wiki/Rushikonda_Beach"], ["List of tourist attractions in Visakhapatnam", "https://en.wikipedia.org/wiki/List_of_tourist_attractions_and_events_in_Visakhapatnam"]],
};

const address = { "@type": "PostalAddress", addressLocality: TRIP.to.city, addressRegion: TRIP.to.state, addressCountry: "IN" };

for (const p of PLACES) {
  const url = URL_ + pageUrl(p);
  const images = p.images.map((im) => URL_ + imgSrc("", p, im, im.widths[1]));
  const jsonLd = {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "WebPage",
        "@id": url + "#webpage",
        url,
        name: `${p.name}, Visakhapatnam · ${TRIP.name}`,
        description: p.summary,
        inLanguage: "en-IN",
        isPartOf: { "@id": URL_ + "#website" },
        about: { "@id": url + "#place" },
        primaryImageOfPage: { "@type": "ImageObject", url: `${URL_}assets/places/${p.id}/og.jpg`, width: 1200, height: 630 },
        breadcrumb: { "@id": url + "#breadcrumb" },
        dateModified: today(),
      },
      {
        "@type": "BreadcrumbList",
        "@id": url + "#breadcrumb",
        itemListElement: [
          { "@type": "ListItem", position: 1, name: TRIP.name, item: URL_ },
          { "@type": "ListItem", position: 2, name: p.name, item: url },
        ],
      },
      {
        "@type": p.type === "TouristAttraction" ? p.type : [p.type, "TouristAttraction"],
        "@id": url + "#place",
        name: p.name,
        alternateName: p.subtitle,
        description: `${p.summary} ${p.about[0]}`,
        url,
        image: images,
        address,
        ...(p.coords && { geo: { "@type": "GeoCoordinates", latitude: p.coords[0], longitude: p.coords[1] } }),
        hasMap: `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(p.map)}`,
        containedInPlace: { "@type": "City", name: TRIP.to.city },
      },
    ],
  };
  const dir = file("places", p.id);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(file("places", p.id, "index.html"), placePage({ SITE, TRIP, PLACES, DAYS, URL_, p, jsonLd, sources: SOURCES[p.id] || [] }));
  for (const im of p.images)
    for (const w of im.widths)
      if (!fs.existsSync(file("assets/places", p.id, `${im.file}-${w}.webp`))) console.warn(`! missing image assets/places/${p.id}/${im.file}-${w}.webp`);
}
// remove pages of places that were taken out of data.js
for (const d of fs.existsSync(file("places")) ? fs.readdirSync(file("places")) : [])
  if (!PLACES.some((p) => p.id === d)) fs.rmSync(file("places", d), { recursive: true, force: true });

// photo credits (CC licences require attribution; it's also shown on every page)
fs.writeFileSync(
  file("assets/places/CREDITS.md"),
  `# Place photo credits

All place photos are from [Wikimedia Commons](https://commons.wikimedia.org) and are used under the licences below.
They were resized, cropped and converted to WebP for the site. Generated by \`tools/places.js\` from \`js/data.js\`.

` +
    PLACES.map(
      (p) =>
        `## ${p.name}

| File | Photo | Author | Licence |
|---|---|---|---|
` +
        p.images.map((im) => `| \`${p.id}/${im.file}\` | [${im.credit.title}](${im.credit.source}) | ${im.credit.author} | [${im.credit.license}](${im.credit.licenseUrl}) |`).join("\n")
    ).join("\n\n") +
    "\n"
);
console.log(`✓ places/  ${PLACES.length} place pages + assets/places/CREDITS.md`);

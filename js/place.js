/* ==========================================================================
   VIZAG EXPRESS — place pages: reveal-on-scroll + photo lightbox.
   The pages are static HTML (generated by tools/places.js); this only adds
   the finishing touches.
   ========================================================================== */
(() => {
  "use strict";
  const $ = (s, r = document) => r.querySelector(s);
  const $$ = (s, r = document) => [...r.querySelectorAll(s)];

  // links to folders (places/x/) need an explicit index.html when the site is opened from disk
  if (location.protocol === "file:")
    $$("a[href]").forEach((a) => {
      const h = a.getAttribute("href");
      if (!/^[a-z]+:|^#/i.test(h) && /\/(#.*)?$/.test(h)) a.setAttribute("href", h.replace(/\/(#.*)?$/, "/index.html$1"));
    });

  // reveal on scroll
  const io = new IntersectionObserver(
    (entries) =>
      entries.forEach((en) => {
        if (!en.isIntersecting) return;
        en.target.classList.add("in-view");
        io.unobserve(en.target);
      }),
    { threshold: 0.12, rootMargin: "0px 0px -6% 0px" }
  );
  $$("[data-reveal]").forEach((el) => io.observe(el));

  // lightbox
  const dlg = $(".lightbox");
  const zooms = $$(".p-zoom");
  if (!dlg || !zooms.length || !dlg.showModal) return;
  const img = $("img", dlg);
  const cap = $("p", dlg);
  let at = 0;
  const show = (k) => {
    at = (k + zooms.length) % zooms.length;
    const b = zooms[at].dataset;
    img.src = b.full;
    img.alt = b.caption;
    cap.textContent = b.caption + " · ";
    const a = document.createElement("a");
    a.href = b.source;
    a.rel = "noopener";
    a.textContent = b.credit;
    a.style.textDecoration = "underline";
    cap.append(a);
    if (!dlg.open) dlg.showModal();
  };
  zooms.forEach((b, k) => b.addEventListener("click", () => show(k)));
  $(".lightbox-close", dlg).addEventListener("click", () => dlg.close());
  $(".lightbox-nav.prev", dlg).addEventListener("click", () => show(at - 1));
  $(".lightbox-nav.next", dlg).addEventListener("click", () => show(at + 1));
  dlg.addEventListener("click", (e) => e.target === dlg && dlg.close()); // click on the backdrop
  dlg.addEventListener("keydown", (e) => {
    if (e.key === "ArrowLeft") show(at - 1);
    if (e.key === "ArrowRight") show(at + 1);
  });
})();
